import {
  Frame,
  SquareStack,
  IdCard,
  PanelTop,
  PanelLeft,
  PanelBottom,
  Heading1,
  Text,
  Image,
  Video,
  MousePointerClick,
  TextCursorInput,
  AlignLeft,
  ChevronsUpDown,
  SquareCheck,
  CircleDot,
  ToggleLeft,
  SlidersHorizontal,
  Plus,
  Table,
  NotebookTabs,
  CircleUser,
  Badge,
  Megaphone,
  PanelTopOpen,
  Minus,
  GalleryHorizontal,
  ChartNoAxesColumn,
  Footprints,
  List,
  Group,
  CirclePlus,
  SquareArrowDown,
  LayoutGrid,
  HelpCircle,
  LucideIcon
} from 'lucide-react';

export const TYPE_ICON_MAP: Record<string, LucideIcon> = {
  page: Frame,
  section: SquareStack,
  card: IdCard,
  navbar: PanelTop,
  sidebar: PanelLeft,
  footer: PanelBottom,
  heading: Heading1,
  para: Text,
  img: Image,
  video: Video,
  button: MousePointerClick,
  input: TextCursorInput,
  textarea: AlignLeft,
  select: ChevronsUpDown,
  checkbox: SquareCheck,
  radio: CircleDot,
  switch: ToggleLeft,
  slider: SlidersHorizontal,
  stepper: Plus,
  table: Table,
  // V52-QUESTION: lucide-react@0.454.0 lacks 'Tabs' export; using NotebookTabs as closest match (§3.2)
  tabs: NotebookTabs,
  avatar: CircleUser,
  badge: Badge,
  banner: Megaphone,
  dialog: PanelTopOpen,
  separator: Minus,
  carousel: GalleryHorizontal,
  stat: ChartNoAxesColumn,
  steps: Footprints,
  nav: List,
  group: Group,
  fab: CirclePlus,
  bottom_sheet: SquareArrowDown,
  scaffold: LayoutGrid
};

export function getTypeIcon(type: string): LucideIcon {
  return TYPE_ICON_MAP[type.toLowerCase()] || HelpCircle;
}
